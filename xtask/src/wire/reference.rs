//! docs/wire/README.md: the document for people, route by route and
//! shape by shape, from the same document (mod.rs writes it).

use std::fmt::Write;

use anyhow::{Context, Result};
use serde_json::{Map, Value};

use super::lock::{type_of, values_of};

/// One line of a doc comment's text, for a table cell or a sentence.
fn flat(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ").replace('|', "\\|")
}

fn about(schema: &Value) -> String {
    schema["description"].as_str().map(flat).unwrap_or_default()
}

/// A type as the lock names it, its components linked.
fn linked(t: &str, names: &Map<String, Value>) -> String {
    let mut out = String::new();
    let mut word = String::new();
    let flush = |word: &mut String, out: &mut String| {
        if !word.is_empty() {
            if names.contains_key(word.as_str()) {
                let _ = write!(out, "[`{word}`](#{})", word.to_ascii_lowercase());
            } else {
                let _ = write!(out, "`{word}`");
            }
            word.clear();
        }
    };
    for c in t.chars() {
        match c {
            '<' | '>' | '|' => {
                flush(&mut word, &mut out);
                out.push_str(match c {
                    '<' => " of ",
                    '>' => "",
                    _ => " or ",
                });
            }
            c => word.push(c),
        }
    }
    flush(&mut word, &mut out);
    out
}

pub fn render(doc: &Value) -> Result<String> {
    let schemas = doc["components"]["schemas"].as_object().context("the document has components")?;
    let mut md = String::from(
        "# The wire\n\n\
         Generated by `cargo xtask wire` from crates/proto (its `src/routes.rs` and\n\
         the types it names): edit those, never this file. [docs/api.md](../api.md)\n\
         says what each route means, who may call it and its limits;\n\
         `crates/proto/wire.lock` holds what an older client relies on\n\
         (`xtask/src/wire/lock.rs`). The same as OpenAPI 3.1: [openapi.json](openapi.json).\n\n\
         ## Routes\n",
    );
    let paths = doc["paths"].as_object().context("the document has paths")?;
    for tag in doc["tags"].as_array().into_iter().flatten() {
        let name = tag["name"].as_str().unwrap_or_default();
        let _ = write!(md, "\n### {name}\n\n{}\n", about(tag));
        let mut ops: Vec<(&str, String, &String, &Value)> = vec![];
        for (path, item) in paths {
            for (method, op) in item.as_object().into_iter().flatten().filter(|(_, op)| op["tags"][0] == name) {
                ops.push((op["operationId"].as_str().unwrap_or_default(), method.to_ascii_uppercase(), path, op));
            }
        }
        ops.sort_by_key(|(id, ..)| *id);
        for (id, method, path, op) in ops {
            let _ = write!(md, "\n#### `{id}`\n\n`{method} {path}`: {}\n\n", op["summary"].as_str().unwrap_or_default());
            let creds: Vec<&str> = op["security"]
                .as_array()
                .into_iter()
                .flatten()
                .map(|s| match s.as_object().and_then(|m| m.keys().next()).map(String::as_str) {
                    Some("nip98") => "NIP-98",
                    Some("session") => "the shell's session",
                    _ => "none",
                })
                .collect();
            let _ = writeln!(md, "- Credentials: {}", creds.join(", "));
            for p in op["parameters"].as_array().into_iter().flatten().filter(|p| p["in"] == "query") {
                let need = if p["required"] == true { "required" } else { "optional" };
                let _ = writeln!(md, "- Query `{}` ({}, {need}): {}", p["name"].as_str().unwrap_or_default(), linked(&type_of(&p["schema"], "query"), schemas), about(p));
            }
            if let Some(body) = op.pointer("/requestBody/content/application~1json/schema") {
                let _ = writeln!(md, "- Body: {}", linked(&type_of(body, id), schemas));
            }
            if let Some(answer) = op.pointer("/responses/200/content/application~1json/schema") {
                let _ = writeln!(md, "- Answer: {}", linked(&type_of(answer, id), schemas));
            }
            if let Some(socket) = op.get("x-fragment-socket") {
                if !socket["sends"].is_null() {
                    let _ = writeln!(md, "- A WebSocket; sends: {}", linked(&type_of(&socket["sends"], id), schemas));
                }
                let _ = writeln!(md, "- A WebSocket; receives: {}", linked(&type_of(&socket["receives"], id), schemas));
            }
            let refusals: Vec<String> = op["responses"]
                .as_object()
                .into_iter()
                .flatten()
                .filter_map(|(status, r)| r.get("x-fragment-codes").map(|c| (status, c)))
                .map(|(status, codes)| {
                    let names: Vec<String> = codes.as_array().into_iter().flatten().map(|c| format!("`{}`", c.as_str().unwrap_or_default())).collect();
                    format!("{status} {}", names.join(", "))
                })
                .collect();
            let _ = writeln!(md, "- Refusals ([`ErrorBody`](#errorbody)): {}", refusals.join("; "));
        }
    }
    md.push_str(
        "\n## Shapes\n\n\
         Each says who writes it: the cell (out: a client reads it), a client\n\
         (in: the cell reads it), or both. An open one's readers read past a\n\
         value they do not know; a closed object refuses a field it does not know.\n",
    );
    for (name, schema) in schemas {
        let dir = schema["x-fragment-direction"].as_str().unwrap_or_default();
        let open = if schema["x-fragment-open"] == true { ", open" } else { "" };
        let closed = if schema["additionalProperties"] == false { ", closed" } else { "" };
        let _ = write!(md, "\n### `{name}`\n\n{dir}{open}{closed}. {}\n", about(schema));
        if let Some(values) = values_of(schema) {
            let _ = writeln!(md, "\nValues: {}.", values.iter().map(|v| format!("`{v}`")).collect::<Vec<_>>().join(", "));
            continue;
        }
        if let Some(variants) = schema["oneOf"].as_array() {
            for v in variants {
                let tag = v["properties"].as_object().and_then(|p| p.iter().find(|(_, s)| s["const"].is_string()));
                let Some((key, value)) = tag else { continue };
                let _ = write!(md, "\n`{key}: {}`. {}\n", value["const"], about(v));
                fields(&mut md, v, Some(key), name, schemas);
            }
            continue;
        }
        fields(&mut md, schema, None, name, schemas);
    }
    Ok(md)
}

/// An object's fields as a table (its tag left out), and what it extends.
fn fields(md: &mut String, schema: &Value, tag: Option<&String>, at: &str, names: &Map<String, Value>) {
    if let Some(base) = schema["$ref"].as_str() {
        let _ = writeln!(md, "\nAnd every field of {}.", linked(base.rsplit('/').next().unwrap_or(base), names));
    }
    let required: Vec<&str> = schema["required"].as_array().into_iter().flatten().filter_map(Value::as_str).collect();
    let props: Vec<(&String, &Value)> = schema["properties"].as_object().into_iter().flatten().filter(|(k, _)| Some(*k) != tag).collect();
    if props.is_empty() {
        return;
    }
    md.push_str("\n| field | type | | |\n| --- | --- | --- | --- |\n");
    for (field, s) in props {
        let need = if required.contains(&field.as_str()) { "required" } else { "optional" };
        let _ = writeln!(md, "| `{field}` | {} | {need} | {} |", linked(&type_of(s, &format!("{at}.{field}")), names), about(s));
    }
}
