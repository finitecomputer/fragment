//! The wire's OpenAPI 3.1 document, from `fragment_proto::routes` and the
//! types they name: the schemas are schemars' (JSON Schema 2020-12, as
//! OpenAPI 3.1 takes them) unchanged, but for `x-fragment-direction` on
//! each component. Two generators make them: answers and the frames a
//! client receives as the cell writes them (serde's serialize contract),
//! requests and the frames a client sends as the cell reads them
//! (deserialize). A type both ways must be one schema both ways.

use anyhow::{bail, Result};
use fragment_proto::routes::{Answer, Auth, ParamAt, Route, ANY_ROUTE, ROUTES, TAGS};
use fragment_proto::{ErrorBody, ErrorCode};
use schemars::generate::SchemaSettings;
use schemars::SchemaGenerator;
use serde_json::{json, Map, Value};

/// Where the components live, as every `$ref` names them.
pub const COMPONENTS: &str = "#/components/schemas/";

/// Who writes a component: the cell (`out`, a client reads it), a client
/// (`in`, the cell reads it), or both.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub enum Direction {
    In,
    Out,
    Both,
}

impl Direction {
    pub fn as_str(self) -> &'static str {
        match self {
            Direction::In => "in",
            Direction::Out => "out",
            Direction::Both => "both",
        }
    }

    pub fn parse(s: &str) -> Option<Direction> {
        [Direction::In, Direction::Out, Direction::Both].into_iter().find(|d| d.as_str() == s)
    }

    pub fn reads_as_out(self) -> bool {
        self != Direction::In
    }

    pub fn reads_as_in(self) -> bool {
        self != Direction::Out
    }
}

pub(super) fn generator(answers: bool) -> SchemaGenerator {
    let mut settings = SchemaSettings::draft2020_12();
    settings.definitions_path = "/components/schemas".into();
    settings.meta_schema = None;
    let settings = if answers { settings.for_serialize() } else { settings.for_deserialize() };
    settings.into_generator()
}

/// The document, as `cargo xtask wire` writes it (keys sorted: serde_json's
/// map is ordered by key here, so the text is the same on every run).
pub fn document() -> Result<Value> {
    let (mut out, mut inn) = (generator(true), generator(false));
    let error_body = out.subschema_for::<ErrorBody>().to_value();
    let mut paths = Map::new();
    for route in ROUTES {
        let op = operation(route, &mut out, &mut inn, &error_body)?;
        let item = paths.entry(route.path.to_string()).or_insert_with(|| json!({}));
        let method = route.method.as_str().to_ascii_lowercase();
        if item.get(&method).is_some() {
            bail!("{} {} is two routes", route.method.as_str(), route.path);
        }
        item[method] = op;
    }
    let schemas = components(out.take_definitions(true), inn.take_definitions(true))?;
    let tags: Vec<Value> = TAGS.iter().map(|(name, about)| json!({ "name": name, "description": about })).collect();
    Ok(json!({
        "openapi": "3.1.0",
        "jsonSchemaDialect": "https://json-schema.org/draft/2020-12/schema",
        "info": {
            "title": "Fragment",
            "version": "1",
            "description": "The routes clients call and the shapes they send and read, generated by `cargo xtask wire` from crates/proto (its routes.rs and the types it names). docs/api.md says what each route means, who may call it, and its limits; crates/proto/wire.lock is what may not change.",
        },
        "tags": tags,
        "paths": paths,
        "components": {
            "schemas": schemas,
            "securitySchemes": {
                "nip98": {
                    "type": "http",
                    "scheme": "Nostr",
                    "description": "NIP-98: `Authorization: Nostr <base64 event>`, a kind-27235 event signed over the method, the URL and the body's SHA-256 (crates/nip98).",
                },
                "session": {
                    "type": "apiKey",
                    "in": "cookie",
                    "name": "__Host-fragment_session",
                    "description": "The shell's session (docs/api.md, Sign-in); `fragment_session` over plain http.",
                },
            },
        },
    }))
}

fn operation(route: &Route, out: &mut SchemaGenerator, inn: &mut SchemaGenerator, error_body: &Value) -> Result<Value> {
    let group = route.operation.split_once('.').map(|(g, _)| g).unwrap_or(route.operation);
    let mut op = json!({
        "operationId": route.operation,
        "tags": [group],
        "summary": route.summary,
        "security": route.auth.iter().map(|a| match a {
            Auth::Nip98 => json!({ "nip98": [] }),
            Auth::Session => json!({ "session": [] }),
            Auth::Anyone => json!({}),
        }).collect::<Vec<_>>(),
    });
    let in_path = |name: &str| route.path.contains(&format!("{{{name}}}"));
    if route.params.iter().any(|p| (p.at == ParamAt::Path) != in_path(p.name)) {
        bail!("{}: a path parameter is one its path names, and only those", route.operation);
    }
    if route.params.iter().any(|p| p.at == ParamAt::Path && !p.required) {
        bail!("{}: a path parameter is required", route.operation);
    }
    if !route.params.is_empty() {
        let params: Vec<Value> = route
            .params
            .iter()
            .map(|p| {
                json!({
                    "name": p.name,
                    "in": match p.at { ParamAt::Path => "path", ParamAt::Query => "query" },
                    "required": p.required,
                    "description": p.doc,
                    "schema": (p.schema)(inn).to_value(),
                })
            })
            .collect();
        op["parameters"] = Value::Array(params);
    }
    if let Some(request) = route.request {
        op["requestBody"] = json!({ "required": true, "content": { "application/json": { "schema": request(inn).to_value() } } });
    }
    let mut responses = Map::new();
    match route.answer {
        Answer::Json(answer) => {
            responses.insert("200".into(), json!({ "description": "OK", "content": { "application/json": { "schema": answer(out).to_value() } } }));
        }
        Answer::Socket { sends, receives } => {
            responses.insert("101".into(), json!({ "description": "Switching Protocols: a WebSocket of JSON text frames (`x-fragment-socket`)." }));
            let sends = sends.map(|s| s(inn).to_value()).unwrap_or(Value::Null);
            op["x-fragment-socket"] = json!({ "sends": sends, "receives": receives(out).to_value() });
        }
    }
    let mut codes: Vec<ErrorCode> = route.errors.iter().chain(ANY_ROUTE.iter()).copied().collect();
    codes.sort_by_key(|c| (c.status(), code_name(*c)));
    codes.dedup();
    for code in codes {
        let status = code.status().to_string();
        let entry = responses.entry(status).or_insert_with(|| {
            json!({ "description": "", "content": { "application/json": { "schema": error_body } }, "x-fragment-codes": [] })
        });
        entry["x-fragment-codes"].as_array_mut().expect("codes are a list").push(json!(code_name(code)));
    }
    for entry in responses.values_mut() {
        if let Some(codes) = entry.get("x-fragment-codes").and_then(Value::as_array) {
            let named: Vec<String> = codes.iter().map(|c| format!("`{}`", c.as_str().unwrap_or_default())).collect();
            entry["description"] = json!(named.join(", "));
        }
    }
    op["responses"] = Value::Object(responses);
    Ok(op)
}

/// A code's name on the wire.
pub fn code_name(code: ErrorCode) -> String {
    serde_json::to_value(code).ok().and_then(|v| v.as_str().map(str::to_string)).expect("an error code is a string")
}

/// The components both generators made, each with who writes it.
pub(super) fn components(answers: Map<String, Value>, requests: Map<String, Value>) -> Result<Map<String, Value>> {
    let mut all = Map::new();
    let mut names: Vec<&String> = answers.keys().chain(requests.keys()).collect();
    names.sort();
    names.dedup();
    for name in names {
        let (schema, direction) = match (answers.get(name), requests.get(name)) {
            (Some(a), Some(r)) if a == r => (a.clone(), Direction::Both),
            (Some(_), Some(_)) => bail!("{name} reads as one shape and writes as another (a `default` without its `skip_serializing_if`, say): a type both ways is one schema both ways, or a request has its own type"),
            (Some(a), None) => (a.clone(), Direction::Out),
            (None, Some(r)) => (r.clone(), Direction::In),
            (None, None) => unreachable!("a name is one generator's"),
        };
        let mut schema = match schema {
            Value::Object(map) => map,
            Value::Bool(true) => Map::new(),
            other => bail!("{name}'s schema is {other}, not an object"),
        };
        schema.insert("x-fragment-direction".into(), json!(direction.as_str()));
        all.insert(name.clone(), Value::Object(schema));
    }
    Ok(all)
}
